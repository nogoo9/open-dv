"""Direct JSON Reference Ontology Loader for EDM Council FIBO packs.

Implements the ReferenceOntologyAdapter SPI protocol adhering to ADR-003 and ADR-004:
- Direct JSON parsing of compiled RFC 8785 JSON packs (fibo-core-<sha256_8>.json)
  generated by offline vendor compiler (scripts/vendor_fibo.py from Task 4C.1)
  and vendored as packaged static data in opendv_sources/fibo/fibo-core-bebd6ae8.json.
- Zero runtime rdflib dependency (satisfying offline-only quarantine for rdflib).
- Sub-70ms cold load latency.
- Sub-18.0 MB peak heap memory footprint.
- O(1) URI lookups for classes and properties.
- Fast candidate search over names, labels, and synonyms.
- Mandatory cryptographic SHA-256 integrity validation against pinned canonical digest.
"""

from __future__ import annotations

import copy
import hashlib
import json
import os
from functools import lru_cache
from pathlib import Path
from typing import Any

from opendv_contracts.errors import ErrorCode
from opendv_contracts.spi.reference_ontology import ReferenceOntologyAdapter
from opendv_sources.exceptions import SourceLoadError, SourceNotFoundError

# Resource Budget Invariants (ADR-003 & docs/21 §3.3)
MAX_DISK_SIZE_BYTES: int = 4 * 1024 * 1024  # < 4.0 MB
MAX_MEMORY_BYTES: int = 18 * 1024 * 1024  # < 18.0 MB
MAX_LOAD_LATENCY_MS: float = 70.0  # < 70.0 ms

# Authoritative Pinned Reference Standards (schemas/v1/baseline-digests.json)
CANONICAL_FIBO_CORE_SHA256: str = "bebd6ae87dfa4eaee523fdeac730f0fe652761004f24e5d15ab36d5225a0acb5"
CANONICAL_FIBO_CORE_PREFIX: str = CANONICAL_FIBO_CORE_SHA256[:8]
CANONICAL_FIBO_CORE_UPSTREAM_COMMIT: str = "69dbbe7a6a4e32049ba3f3988b48877bc954f061"
CANONICAL_FIBO_CORE_UPSTREAM_TAG: str = "master_2024Q4"


class ReferenceOntologyCorruptError(SourceLoadError, ValueError):
    """Raised when a reference ontology pack digest mismatches baseline or is corrupted."""

    error_code = ErrorCode.SOURCE_LOAD_ERROR
    exit_code = 4
    http_status = 422

    def __init__(
        self,
        message: str,
        *,
        pack_path: Path | str | None = None,
        expected_sha256: str | None = None,
        computed_sha256: str | None = None,
        details: dict[str, Any] | None = None,
    ) -> None:
        merged_details = dict(details or {})
        if pack_path is not None:
            merged_details["pack_path"] = str(pack_path)
        if expected_sha256 is not None:
            merged_details["expected_sha256"] = expected_sha256
        if computed_sha256 is not None:
            merged_details["computed_sha256"] = computed_sha256
        merged_details["error_code_symbol"] = "REFERENCE_ONTOLOGY_CORRUPT"
        super().__init__(message, details=merged_details)
        self.exit_code = 4
        self.http_status = 422
        self.error_code_symbol = "REFERENCE_ONTOLOGY_CORRUPT"


def _copy_entity(data: dict[str, Any], entity_type: str | None = None) -> dict[str, Any]:
    """Create a genuine deep copy of an entity dict protecting internal state (MIN-01)."""
    res = copy.deepcopy(data)
    if entity_type is not None:
        res["entity_type"] = entity_type
    return res


def _find_default_pack_path() -> Path:
    """Locate the default packaged FIBO core pack JSON file (MIN-05)."""
    # 1. Explicit environment variable override
    env_override = os.environ.get("OPENDV_FIBO_PACK_PATH")
    if env_override:
        p = Path(env_override).resolve()
        if not p.is_file():
            msg = (
                f"Configured OPENDV_FIBO_PACK_PATH not found or not a regular file: {env_override}"
            )
            raise SourceNotFoundError(msg)
        return p

    # 2. Package directory adjacent to this loader module
    pkg_dir = Path(__file__).resolve().parent

    # Check for canonical pattern fibo-core-<sha256_8>.json matching canonical prefix
    exact_canonical = pkg_dir / f"fibo-core-{CANONICAL_FIBO_CORE_PREFIX}.json"
    if exact_canonical.is_file():
        return exact_canonical

    # Check for alias fibo-core-pack.json
    alias_pack = pkg_dir / "fibo-core-pack.json"
    if alias_pack.is_file():
        return alias_pack

    msg = (
        f"Default FIBO reference ontology pack ('fibo-core-{CANONICAL_FIBO_CORE_PREFIX}.json' "
        f"or 'fibo-core-pack.json') not found in {pkg_dir}"
    )
    raise SourceNotFoundError(msg)


def _find_baseline_digests_path() -> Path | None:
    """Attempt to locate schemas/v1/baseline-digests.json from the package/repo root.

    Security notice: Anchored strictly relative to this loader module location (or
    OPENDV_BASELINE_DIGESTS_PATH env var) to prevent directory traversal or spoofed
    baseline injection from untrusted pack directories (MAJ-01).
    """
    env_override = os.environ.get("OPENDV_BASELINE_DIGESTS_PATH")
    if env_override:
        p = Path(env_override).resolve()
        if not p.is_file():
            msg = (
                f"Configured OPENDV_BASELINE_DIGESTS_PATH not found or "
                f"not a regular file: {env_override}"
            )
            raise SourceNotFoundError(msg)
        return p

    start_dir = Path(__file__).resolve().parent
    current: Path | None = start_dir

    for _ in range(8):
        if current is None:
            break
        candidate = current / "schemas" / "v1" / "baseline-digests.json"
        if candidate.is_file():
            return candidate
        parent = current.parent
        if parent == current:
            break
        current = parent

    return None


class FiboReferenceOntologyLoader(ReferenceOntologyAdapter):
    """Direct JSON Reference Ontology Loader implementing ReferenceOntologyAdapter SPI.

    Adheres strictly to ADR-003 and ADR-004:
    - Pure Python standard library JSON loading with ZERO runtime rdflib imports.
    - Cold load completes in < 70 ms with < 18.0 MB peak memory.
    - O(1) dictionary lookup by URI.
    - Fast prefix, token, and substring candidate search.
    - Mandatory cryptographic digest integrity verification.
    """

    def __init__(
        self,
        pack_path: str | Path | None = None,
        *,
        expected_sha256: str | None = None,
        verify_integrity: bool = True,
    ) -> None:
        """Initialize the FIBO loader from a pre-compiled JSON pack.

        Args:
            pack_path: Path to the fibo-core pack JSON file. If None, resolves the packaged pack.
            expected_sha256: Optional full 64-char or 8-char prefix SHA-256 digest to verify.
            verify_integrity: Whether to verify filename hash prefix and baseline digests.

        Raises:
            SourceNotFoundError: If pack file does not exist.
            ReferenceOntologyCorruptError: If pack integrity or schema validation fails.
        """
        resolved_path = (
            Path(pack_path).resolve() if pack_path is not None else _find_default_pack_path()
        )

        if not resolved_path.is_file():
            msg = f"Reference ontology pack file not found: {resolved_path}"
            raise SourceNotFoundError(msg)

        try:
            with open(resolved_path, "rb") as f:
                raw_bytes = f.read(MAX_DISK_SIZE_BYTES + 1)
        except FileNotFoundError as err:
            msg = f"Reference ontology pack file not found: {resolved_path}"
            raise SourceNotFoundError(msg) from err
        except OSError as err:
            msg = f"Failed to read reference ontology pack from {resolved_path}: {err}"
            raise ReferenceOntologyCorruptError(msg, pack_path=resolved_path) from err

        if len(raw_bytes) > MAX_DISK_SIZE_BYTES:
            msg = (
                f"Pack disk size {len(raw_bytes)} bytes exceeds budget of "
                f"{MAX_DISK_SIZE_BYTES} bytes (<4.0 MB)"
            )
            raise ReferenceOntologyCorruptError(
                msg,
                pack_path=resolved_path,
            )

        computed_sha256 = hashlib.sha256(raw_bytes).hexdigest()
        computed_prefix = computed_sha256[:8]

        # Verify filename pattern if named fibo-core-<sha256_8>.json
        if verify_integrity:
            filename = resolved_path.name
            if (
                filename.startswith("fibo-core-")
                and filename.endswith(".json")
                and filename != "fibo-core-pack.json"
            ):
                expected_prefix = filename.removeprefix("fibo-core-").removesuffix(".json")
                if len(expected_prefix) == 8 and expected_prefix != computed_prefix:
                    msg = (
                        f"Filename hash prefix '{expected_prefix}' does not match "
                        f"computed digest '{computed_prefix}'"
                    )
                    raise ReferenceOntologyCorruptError(
                        msg,
                        pack_path=resolved_path,
                        expected_sha256=expected_prefix,
                        computed_sha256=computed_sha256,
                    )

        # Verify explicit expected_sha256 parameter if provided
        if expected_sha256 is not None:
            norm_expected = expected_sha256.strip().lower()
            if len(norm_expected) == 64:
                if norm_expected != computed_sha256:
                    msg = (
                        f"Pack digest '{computed_sha256}' does not match "
                        f"expected digest '{norm_expected}'"
                    )
                    raise ReferenceOntologyCorruptError(
                        msg,
                        pack_path=resolved_path,
                        expected_sha256=norm_expected,
                        computed_sha256=computed_sha256,
                    )
            elif len(norm_expected) == 8:
                if norm_expected != computed_prefix:
                    msg = (
                        f"Pack digest prefix '{computed_prefix}' does not match "
                        f"expected prefix '{norm_expected}'"
                    )
                    raise ReferenceOntologyCorruptError(
                        msg,
                        pack_path=resolved_path,
                        expected_sha256=norm_expected,
                        computed_sha256=computed_sha256,
                    )
            else:
                msg = (
                    f"Invalid expected_sha256 length ({len(norm_expected)}): "
                    "must be 8 or 64 characters"
                )
                raise ReferenceOntologyCorruptError(
                    msg,
                    pack_path=resolved_path,
                    expected_sha256=norm_expected,
                    computed_sha256=computed_sha256,
                )

        # Parse JSON payload directly from bytes (SUG-01)
        try:
            data = json.loads(raw_bytes)
        except (json.JSONDecodeError, UnicodeDecodeError) as err:
            msg = f"Failed to parse pack JSON: {err}"
            raise ReferenceOntologyCorruptError(
                msg,
                pack_path=resolved_path,
                computed_sha256=computed_sha256,
            ) from err
        finally:
            del raw_bytes

        if not isinstance(data, dict):
            msg = f"Pack root must be a JSON object, got {type(data).__name__}"
            raise ReferenceOntologyCorruptError(
                msg,
                pack_path=resolved_path,
                computed_sha256=computed_sha256,
            )

        # Verify required sections
        classes = data.get("classes")
        properties = data.get("properties")
        metadata = data.get("metadata")

        if (
            not isinstance(classes, dict)
            or not isinstance(properties, dict)
            or not isinstance(metadata, dict)
        ):
            msg = "Pack must contain 'classes', 'properties', and 'metadata' as JSON objects"
            raise ReferenceOntologyCorruptError(
                msg,
                pack_path=resolved_path,
                computed_sha256=computed_sha256,
            )

        if not classes or not properties:
            msg = "Pack 'classes' or 'properties' collection is unexpectedly empty"
            raise ReferenceOntologyCorruptError(
                msg,
                pack_path=resolved_path,
                computed_sha256=computed_sha256,
            )

        # Enforce required metadata fields (MIN-08)
        if "version" not in metadata or not isinstance(metadata["version"], str):
            msg = "Pack metadata missing valid 'version' string"
            raise ReferenceOntologyCorruptError(
                msg, pack_path=resolved_path, computed_sha256=computed_sha256
            )
        if "pack_id" not in metadata or not isinstance(metadata["pack_id"], str):
            msg = "Pack metadata missing valid 'pack_id' string"
            raise ReferenceOntologyCorruptError(
                msg, pack_path=resolved_path, computed_sha256=computed_sha256
            )

        # Detailed schema validation of entries and element types (MIN-02, MIN-05)
        for c_uri, c_val in classes.items():
            if not isinstance(c_val, dict) or c_val.get("uri") != c_uri:
                msg = f"Malformed class entry for URI '{c_uri}': must be dict with matching uri"
                raise ReferenceOntologyCorruptError(
                    msg, pack_path=resolved_path, computed_sha256=computed_sha256
                )
            if "label" in c_val and not isinstance(c_val["label"], str):
                msg = f"Class entry '{c_uri}' label must be a string"
                raise ReferenceOntologyCorruptError(
                    msg, pack_path=resolved_path, computed_sha256=computed_sha256
                )
            sub_classes = c_val.get("sub_class_of", [])
            if not isinstance(sub_classes, list) or not all(
                isinstance(x, str) for x in sub_classes
            ):
                msg = f"Class entry '{c_uri}' sub_class_of must be a list of strings"
                raise ReferenceOntologyCorruptError(
                    msg, pack_path=resolved_path, computed_sha256=computed_sha256
                )
            synonyms = c_val.get("synonyms", [])
            if not isinstance(synonyms, list) or not all(isinstance(x, str) for x in synonyms):
                msg = f"Class entry '{c_uri}' synonyms must be a list of strings"
                raise ReferenceOntologyCorruptError(
                    msg, pack_path=resolved_path, computed_sha256=computed_sha256
                )

        for p_uri, p_val in properties.items():
            if not isinstance(p_val, dict) or p_val.get("uri") != p_uri:
                msg = f"Malformed property entry for URI '{p_uri}': must be dict with matching uri"
                raise ReferenceOntologyCorruptError(
                    msg, pack_path=resolved_path, computed_sha256=computed_sha256
                )
            if "label" in p_val and not isinstance(p_val["label"], str):
                msg = f"Property entry '{p_uri}' label must be a string"
                raise ReferenceOntologyCorruptError(
                    msg, pack_path=resolved_path, computed_sha256=computed_sha256
                )
            p_synonyms = p_val.get("synonyms", [])
            if not isinstance(p_synonyms, list) or not all(isinstance(x, str) for x in p_synonyms):
                msg = f"Property entry '{p_uri}' synonyms must be a list of strings"
                raise ReferenceOntologyCorruptError(
                    msg, pack_path=resolved_path, computed_sha256=computed_sha256
                )

        # Mandatory authoritative integrity verification (MAJ-01, MAJ-02)
        if verify_integrity:
            # Full 64-char match against pinned canonical digest is ALWAYS enforced (MAJ-01)
            if computed_sha256 != CANONICAL_FIBO_CORE_SHA256:
                msg = (
                    f"Pack SHA-256 '{computed_sha256}' does not match "
                    f"authoritative canonical FIBO digest '{CANONICAL_FIBO_CORE_SHA256}'"
                )
                raise ReferenceOntologyCorruptError(
                    msg,
                    pack_path=resolved_path,
                    expected_sha256=CANONICAL_FIBO_CORE_SHA256,
                    computed_sha256=computed_sha256,
                )

            baseline_path = _find_baseline_digests_path()
            if baseline_path is not None:
                try:
                    baseline_raw = baseline_path.read_text(encoding="utf-8")
                    baseline_data = json.loads(baseline_raw)
                except (json.JSONDecodeError, OSError) as err:
                    msg = (
                        f"Authoritative baseline digests file at {baseline_path} "
                        f"is corrupted: {err}"
                    )
                    raise ReferenceOntologyCorruptError(
                        msg, pack_path=resolved_path, computed_sha256=computed_sha256
                    ) from err

                if not isinstance(baseline_data, dict):
                    msg = f"Baseline digests root must be a JSON object in {baseline_path}"
                    raise ReferenceOntologyCorruptError(
                        msg, pack_path=resolved_path, computed_sha256=computed_sha256
                    )

                ref_packs = baseline_data.get("reference_packs")
                if not isinstance(ref_packs, dict):
                    msg = f"Baseline digests missing 'reference_packs' object in {baseline_path}"
                    raise ReferenceOntologyCorruptError(
                        msg, pack_path=resolved_path, computed_sha256=computed_sha256
                    )

                fibo_core_spec = ref_packs.get("fibo_core")
                if not isinstance(fibo_core_spec, dict):
                    msg = f"Baseline digests missing 'fibo_core' reference pack in {baseline_path}"
                    raise ReferenceOntologyCorruptError(
                        msg, pack_path=resolved_path, computed_sha256=computed_sha256
                    )

                expected_commit = fibo_core_spec.get("upstream_commit")
                if expected_commit and metadata.get("upstream_commit") != expected_commit:
                    msg = (
                        f"Pack upstream commit '{metadata.get('upstream_commit')}' "
                        f"does not match baseline commit '{expected_commit}'"
                    )
                    raise ReferenceOntologyCorruptError(
                        msg,
                        pack_path=resolved_path,
                        computed_sha256=computed_sha256,
                    )

                canon_sha = fibo_core_spec.get("canonical_sha256")
                if not canon_sha:
                    canon_sha = CANONICAL_FIBO_CORE_SHA256
                elif not isinstance(canon_sha, str):
                    msg = "Malformed 'canonical_sha256' in baseline digests: must be string"
                    raise ReferenceOntologyCorruptError(
                        msg, pack_path=resolved_path, computed_sha256=computed_sha256
                    )
                if canon_sha.lower() != CANONICAL_FIBO_CORE_SHA256:
                    msg = (
                        f"Authoritative baseline digest '{canon_sha}' does not match "
                        f"pinned canonical FIBO digest '{CANONICAL_FIBO_CORE_SHA256}'"
                    )
                    raise ReferenceOntologyCorruptError(
                        msg,
                        pack_path=resolved_path,
                        expected_sha256=CANONICAL_FIBO_CORE_SHA256,
                        computed_sha256=canon_sha,
                    )

        # Build in-memory indexes (completed in < 1 ms)
        self._pack_path: Path = resolved_path
        self._pack_sha256: str = computed_sha256
        self._classes: dict[str, dict[str, Any]] = classes
        self._properties: dict[str, dict[str, Any]] = properties
        self._metadata: dict[str, Any] = metadata

        # Pre-index taxonomy hierarchy: parent_uri -> list of child_uris
        subclass_map: dict[str, list[str]] = {}
        for c_uri, c_val in classes.items():
            for p_uri in c_val.get("sub_class_of", []):
                subclass_map.setdefault(p_uri, []).append(c_uri)
        self._subclass_index: dict[str, list[str]] = subclass_map

    @classmethod
    def load(
        cls,
        pack_path: str | Path | None = None,
        *,
        expected_sha256: str | None = None,
        verify_integrity: bool = True,
    ) -> FiboReferenceOntologyLoader:
        """Factory method to instantiate a FiboReferenceOntologyLoader."""
        return cls(
            pack_path=pack_path,
            expected_sha256=expected_sha256,
            verify_integrity=verify_integrity,
        )

    # -------------------------------------------------------------------------
    # ReferenceOntologyAdapter SPI Implementation
    # -------------------------------------------------------------------------

    def lookup_by_uri(self, uri: str) -> dict[str, Any] | None:
        """Look up entity definition, label, and metadata by exact standard URI.

        Provides O(1) retrieval for classes and properties in the reference pack.

        Args:
            uri: Fully-qualified reference ontology URI.

        Returns:
            Dictionary containing entity definition, label, synonyms, and taxonomy,
            or None if the URI is not present in the pack.
        """
        match = self._classes.get(uri)
        entity_type = "class"
        if match is None:
            match = self._properties.get(uri)
            entity_type = "property"
        if match is None:
            return None
        return _copy_entity(match, entity_type=entity_type)

    def search_candidates(self, term: str, limit: int = 10) -> list[dict[str, Any]]:
        """Search reference ontology candidates matching search term or token.

        Performs fast multi-tier matching (exact, prefix, token, substring)
        over concept labels, local names, and synonyms across both classes
        and properties, ensuring higher-ranked matches always outrank lower-ranked
        matches (MAJ-01, MAJ-02).

        Args:
            term: Search query or token.
            limit: Maximum candidate entries to return (default: 10).

        Returns:
            Ranked list of matching entity dictionaries.
        """
        if limit <= 0:
            return []

        clean_term = term.strip().lower()
        if not clean_term:
            return []

        tokens = clean_term.split()
        exact_matches: list[tuple[dict[str, Any], str]] = []
        prefix_matches: list[tuple[dict[str, Any], str]] = []
        token_matches: list[tuple[dict[str, Any], str]] = []
        substring_matches: list[tuple[dict[str, Any], str]] = []
        seen_uris: set[str] = set()

        def _evaluate_collection(entries: dict[str, dict[str, Any]], entity_type: str) -> None:
            for uri, data in entries.items():
                if uri in seen_uris:
                    continue
                label = str(data.get("label", "")).lower()
                local_name = uri.rsplit("/", 1)[-1].rsplit("#", 1)[-1].lower()
                synonyms = [str(s).lower() for s in data.get("synonyms", [])]

                # 1. Exact match (score = 1.0)
                if clean_term in (label, local_name) or clean_term in synonyms:
                    exact_matches.append((data, entity_type))
                    seen_uris.add(uri)
                    continue

                # 2. Prefix match (score = 0.85)
                if (
                    label.startswith(clean_term)
                    or local_name.startswith(clean_term)
                    or any(s.startswith(clean_term) for s in synonyms)
                ):
                    prefix_matches.append((data, entity_type))
                    seen_uris.add(uri)
                    continue

                # 3. Multi-word token match (score = 0.70)
                if len(tokens) > 1 and all(
                    w in label or w in local_name or any(w in s for s in synonyms) for w in tokens
                ):
                    token_matches.append((data, entity_type))
                    seen_uris.add(uri)
                    continue

                # 4. Substring contains match (score = 0.50)
                if (
                    clean_term in label
                    or clean_term in local_name
                    or any(clean_term in s for s in synonyms)
                ):
                    substring_matches.append((data, entity_type))
                    seen_uris.add(uri)
                    continue

        # Evaluate classes first
        _evaluate_collection(self._classes, "class")

        # Always evaluate properties unless exact class matches alone fill limit (MAJ-02)
        if len(exact_matches) < limit:
            _evaluate_collection(self._properties, "property")

        # Sort tier-wise: classes prioritized on equal score, then shorter labels, then label
        def _sort_key(item: tuple[dict[str, Any], str]) -> tuple[int, int, str]:
            ent_type_order = 0 if item[1] == "class" else 1
            label = str(item[0].get("label", ""))
            return (ent_type_order, len(label), label)

        exact_matches.sort(key=_sort_key)
        prefix_matches.sort(key=_sort_key)
        token_matches.sort(key=_sort_key)
        substring_matches.sort(key=_sort_key)

        combined: list[tuple[float, tuple[dict[str, Any], str]]] = (
            [(1.00, m) for m in exact_matches]
            + [(0.85, m) for m in prefix_matches]
            + [(0.70, m) for m in token_matches]
            + [(0.50, m) for m in substring_matches]
        )
        results: list[dict[str, Any]] = []

        # Only deep-copy the truncated final top limit results (SUG-01)
        for score, (data, ent_type) in combined[:limit]:
            entry = _copy_entity(data, entity_type=ent_type)
            entry["match_score"] = score
            results.append(entry)

        return results

    # -------------------------------------------------------------------------
    # Inspection & Taxonomy Resolution Helpers
    # -------------------------------------------------------------------------

    def get_classes(self) -> dict[str, dict[str, Any]]:
        """Return all classes mapped by URI (deep copied to prevent mutation)."""
        return {k: _copy_entity(v, entity_type="class") for k, v in self._classes.items()}

    def get_properties(self) -> dict[str, dict[str, Any]]:
        """Return all properties mapped by URI (deep copied to prevent mutation)."""
        return {k: _copy_entity(v, entity_type="property") for k, v in self._properties.items()}

    def get_pack_metadata(self) -> dict[str, Any]:
        """Return the compiled pack metadata dictionary."""
        return _copy_entity(self._metadata)

    def get_direct_superclasses(self, uri: str) -> list[str]:
        """Return direct rdfs:subClassOf parent URIs for a given class URI."""
        class_entry = self._classes.get(uri)
        if not class_entry:
            return []
        return list(class_entry.get("sub_class_of", []))

    def get_direct_subclasses(self, uri: str) -> list[str]:
        """Return direct child class URIs inheriting from the given class URI."""
        return list(self._subclass_index.get(uri, []))

    # -------------------------------------------------------------------------
    # Properties
    # -------------------------------------------------------------------------

    @property
    def pack_sha256(self) -> str:
        """Full 64-character hexadecimal SHA-256 digest of the loaded pack."""
        return self._pack_sha256

    @property
    def pack_sha256_prefix(self) -> str:
        """8-character hexadecimal prefix of the pack SHA-256 digest."""
        return self._pack_sha256[:8]

    @property
    def pack_id(self) -> str:
        """Registered pack identifier (e.g. 'fibo-core')."""
        return str(self._metadata["pack_id"])

    @property
    def version(self) -> str:
        """Pack version string (e.g. '1.0.0')."""
        return str(self._metadata["version"])

    @property
    def modules(self) -> list[str]:
        """List of FIBO core module acronyms contained in this pack."""
        raw_modules = self._metadata.get("modules", [])
        return [str(m) for m in raw_modules]

    @property
    def class_count(self) -> int:
        """Total number of classes defined in this pack."""
        return len(self._classes)

    @property
    def property_count(self) -> int:
        """Total number of properties defined in this pack."""
        return len(self._properties)

    @property
    def pack_path(self) -> Path:
        """Absolute file path to the loaded pack."""
        return self._pack_path


@lru_cache(maxsize=8)
def _get_cached_fibo_loader(
    path_str: str,
    norm_expected_sha: str | None,
    verify: bool,
    mtime: float,
    size: int,
    baseline_path_str: str | None = None,
    baseline_mtime: float = 0.0,
) -> FiboReferenceOntologyLoader:
    """Internal LRU-cached instance helper keyed on path, digest, verify, and stat."""
    return FiboReferenceOntologyLoader(
        pack_path=Path(path_str),
        expected_sha256=norm_expected_sha,
        verify_integrity=verify,
    )


def clear_fibo_loader_cache() -> None:
    """Clear the LRU cache of loaded FIBO loaders (MIN-03)."""
    _get_cached_fibo_loader.cache_clear()


def get_default_fibo_loader(
    pack_path: str | Path | None = None,
    *,
    expected_sha256: str | None = None,
    verify_integrity: bool = True,
) -> FiboReferenceOntologyLoader:
    """Get a cached or newly initialized FiboReferenceOntologyLoader instance."""
    resolved_path = (
        Path(pack_path).resolve() if pack_path is not None else _find_default_pack_path()
    )
    if not resolved_path.is_file():
        msg = f"Reference ontology pack file not found: {resolved_path}"
        raise SourceNotFoundError(msg)

    try:
        stat = resolved_path.stat()
    except FileNotFoundError as err:
        msg = f"Reference ontology pack file not found: {resolved_path}"
        raise SourceNotFoundError(msg) from err

    baseline_path = _find_baseline_digests_path()
    baseline_path_str: str | None = str(baseline_path) if baseline_path is not None else None
    baseline_mtime: float = 0.0
    if baseline_path is not None:
        try:
            baseline_mtime = baseline_path.stat().st_mtime
        except OSError:
            baseline_mtime = 0.0

    norm_sha = expected_sha256.strip().lower() if expected_sha256 else None
    return _get_cached_fibo_loader(
        str(resolved_path),
        norm_sha,
        verify_integrity,
        stat.st_mtime,
        stat.st_size,
        baseline_path_str,
        baseline_mtime,
    )


